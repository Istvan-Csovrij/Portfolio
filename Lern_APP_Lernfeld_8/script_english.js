function saveToLocalStorage() {
    localStorage.setItem("kartenDaten_eng", JSON.stringify(kartenDaten_eng));
}

function loadFromLocalStorage() {
    const storedData = localStorage.getItem(kartenDaten_eng);
    if (!storedData) return;
    const parsedData = JSON.parse(storedData);
    kartenDaten_eng.length = 0;
    parsedData.forEach(karte => kartenDaten_eng.push(karte));
}


